def sn(v):
    """Snap to KiCad's 1.27 mm connection grid (see can-iso-breakout)."""
    return round(round(v / GRID) * GRID, 4)


def fp(path):
    """Footprint id, checked to exist on disk."""
    lib, name = path.split(":", 1)
    for root in (LOCALFP, FPROOT):
        if os.path.exists(os.path.join(root, lib + ".pretty", name + ".kicad_mod")):
            return path
    raise FileNotFoundError("no such footprint: " + path)


def rv(ohms):
    """Resistor value in the usual shorthand: 9760 -> 9k76, 1e6 -> 1M."""
    for div, suf in ((1e6, "M"), (1e3, "k"), (1.0, "R")):
        if ohms >= div:
            s = f"{ohms/div:.3g}"
            if "." in s:
                a, b = s.split(".")
                return f"{a}{suf}{b}"
            return f"{s}{suf}"
    return f"{ohms}R"


def cv(f):
    for div, suf in ((1e-6, "u"), (1e-9, "n"), (1e-12, "p")):
        if f >= div:
            s = f"{f/div:.3g}"
            if "." in s:
                a, b = s.split(".")
                return f"{a}{suf}{b}"
            return f"{s}{suf}"
    return str(f)


