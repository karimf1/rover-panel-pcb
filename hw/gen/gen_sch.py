def gnd_at(x, y, rot=0):
    """Ground symbol whose pin is at (x, y), pointing AWAY along the stub.

    A ground symbol always drawn downward lands on the next pin's label on
    any part with pins stacked on 2.54 mm -- every connector on this sheet.
    """
    _pwr[0] += 1
    sch.sym("power", "GND", "#PWR%03d" % _pwr[0], x, y, rot=rot, value="GND",
            hide_ref=True, hide_value=True, ref_dy=-3.81, val_dy=3.81, in_bom=False)


def flag_net(net, x, y):
    """PWR_FLAG on a labelled stub: tells ERC this net has a source."""
    x, y = sn(x), sn(y)
    _pwr[0] += 1
    sch.sym("power", "PWR_FLAG", "#FLG%03d" % _pwr[0], x, y, value="PWR_FLAG",
            hide_ref=True, hide_value=True, in_bom=False)
    sch.wire(x, y, x, y + 5.08)
    if net == "GND":
        gnd_at(x, y + 5.08)
    else:
        sch.label(net, x, y + 5.08, rot=270, justify="right bottom")


def part(lib, name, ref, x, y, nets, rot=0, value=None, footprint=None,
         fields=(), unit=1, stub=2.54, in_bom=True, hide_value=False):
    """Place a symbol and wire EVERY listed pin to its net.

    `nets` maps pin number -> net name, "GND", or None for a no-connect.
    A pin missing from `nets` is an error: an unconnected pin on this board
    should be a decision, not an omission.
    """
    x, y = sn(x), sn(y)
    p = sch.sym(lib, name, ref, x, y, rot=rot, value=value, footprint=footprint,
                fields=fields, unit=unit, in_bom=in_bom, hide_value=hide_value,
                ref_dy=-6.35 if rot in (0, 180) else -2.54,
                val_dy=6.35 if rot in (0, 180) else 2.54)
    units = kisch.symlib.pin_units(lib, name)
    multi = len({u for u in units.values() if u}) > 1
    mine = [num for num in units if not multi or units[num] in (0, unit)]
    missing = [n for n in mine if n not in nets]
    if missing:
        raise SystemExit(f"{ref}: pins {missing} have no net assigned")
    done = set()
    for num in mine:
        net = nets[num]
        px, py = p(num)
        if (px, py) in done:        # stacked pins (LM5165 GND + pad)
            NETS_SEEN.setdefault(net, set()).add((ref, num))
            continue
        done.add((px, py))
        if net is None:
            sch.no_connect(px, py)
            continue
        NETS_SEEN.setdefault(net, set()).add((ref, num))
        cx, cy = p.at
        dx, dy = px - cx, py - cy
        if abs(dx) >= abs(dy):
            ux, uy = (1 if dx >= 0 else -1), 0
        else:
            ux, uy = 0, (1 if dy >= 0 else -1)
        ex, ey = round(px + ux * stub, 4), round(py + uy * stub, 4)
        sch.wire(px, py, ex, ey)
        if net == "GND":
            gnd_at(ex, ey, {(1, 0): 90, (-1, 0): 270, (0, -1): 180}.get((ux, uy), 0))
        elif ux == 1:
            sch.label(net, ex, ey, rot=0, justify="left bottom")
        elif ux == -1:
            sch.label(net, ex, ey, rot=180, justify="right bottom")
        elif uy == -1:
            sch.label(net, ex, ey, rot=90, justify="left bottom")
        else:
            sch.label(net, ex, ey, rot=270, justify="right bottom")
    return p


def R(ref, x, y, a, b, ohms, tol=None, note=None, pkg=R0805):
    f = [("Tolerance", tol)] if tol else []
    if note:
        f.append(("Note", note))
    return part("Device", "R", ref, x, y, {"1": a, "2": b}, rot=90,
                value=rv(ohms) + (f" {tol}" if tol else ""), footprint=pkg, fields=f)


def Cap(ref, x, y, a, b, farads, volts, pkg=C0805, note=None):
    f = [("Voltage", f"{volts} V")]
    if note:
        f.append(("Note", note))
    return part("Device", "C", ref, x, y, {"1": a, "2": b}, rot=90,
                value=f"{cv(farads)} {volts}V", footprint=pkg, fields=f)


def nfet(ref, x, y, g, d, s="GND", note=None):
    f = [("MPN", "2N7002K")] + ([("Note", note)] if note else [])
    return part("Transistor_FET", "2N7002", ref, x, y, {"1": g, "3": d, "2": s},
                value="2N7002K", footprint=SOT23, fields=f)


def group(x1, y1, x2, y2, title, *notes):
    sch.rect(x1, y1, x2, y2)
    sch.text(title, x1 + 1, y1 - 1.5, size=2.2)
    for i, n in enumerate(notes):
        sch.text(n, x1 + 1, y2 + 4 + 3.6 * i, size=1.5)


