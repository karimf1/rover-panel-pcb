"""Generate rover-panel-supervisor.kicad_sch.

The netlist is written as data -- NETS below, one row per part, pin -> net --
and the drawing is derived from it: every pin gets a short outward stub ending
in a net label, a ground symbol or a no-connect flag.  That makes the sheet a
readable netlist rather than a wiring puzzle, and it means the thing
check_interlock.py proves things about is exactly the thing that was typed.

The schematic is grouped by what each block is FOR, and each group carries
the one sentence of reasoning a reviewer would otherwise have to ask for.

Values come from design/spec.py wherever the design maths chose them, so a
resistor cannot be changed on the sheet without the calculation seeing it.
"""
